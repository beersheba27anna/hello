# sequence [start:stop:step]
# start - inclusive
# stop - exclusive
# step - step for sequence

str = "Hello"
print(str[1]) #
print(str[1:3]) #el
print(str[1:3:-1]) #empty
print(str[-1]) #o
print(str[-1:3]) #empty
print(str[:]) # copy - Hello
print(str[::-1]) # reverse copy
print(str[4:-6:-1]) # reverse copy
print(range(20)[3])
print(range(20)[::-1])